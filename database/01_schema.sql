CREATE DATABASE RoomRentalInterview;
GO
USE RoomRentalInterview;
GO
CREATE TABLE Rooms (RoomId INT IDENTITY PRIMARY KEY, Name NVARCHAR(100) NOT NULL, MonthlyRent DECIMAL(10,2) NOT NULL, IsAvailable BIT NOT NULL DEFAULT 1);
CREATE TABLE Tenants (TenantId INT IDENTITY PRIMARY KEY, FullName NVARCHAR(150) NOT NULL, Phone NVARCHAR(30) NULL);
CREATE TABLE Bookings (BookingId INT IDENTITY PRIMARY KEY, RoomId INT NOT NULL REFERENCES Rooms(RoomId), TenantId INT NOT NULL REFERENCES Tenants(TenantId), CheckIn DATE NOT NULL, CheckOut DATE NOT NULL, Status NVARCHAR(20) NOT NULL);
GO
